export function message(value: string) {
  if (ka[value]) return ka[value];
  const pairs = [
    ["Type mismatch: ", "ტიპები შეუთავსებელია: "],
    ["Connect ", "შეაერთეთ: "],
    ["Waiting for ", "ელოდება: "],
    ["Unknown function: ", "უცნობი ფუნქცია: "],
    ["Unknown variable: ", "უცნობი ცვლადი: "],
    ["Unexpected token: ", "მოულოდნელი ელემენტი: "],
    ["Unexpected character at ", "მოულოდნელი სიმბოლოს პოზიცია: "],
    ["Invalid ", "არასწორია: "],
    [
      "Multiple connections are not supported on ",
      "რამდენიმე კავშირი დაუშვებელია პორტზე: ",
    ],
  ];
  for (const [en, kaText] of pairs)
    if (value.startsWith(en))
      return (
        kaText +
        value
          .slice(en.length)
          .replace(". Use a, b or t.", ". გამოიყენეთ a, b ან t.")
      );
  const input = value.match(/^Input (.+) expects (.+)$/);
  if (input) return "შემავალი " + input[1] + " მოითხოვს: " + L(input[2]);
  const arity = value.match(/^(.+) expects (.+) arguments?$/);
  if (arity) return arity[1] + " მოითხოვს არგუმენტების რაოდენობას: " + arity[2];
  return value;
}
